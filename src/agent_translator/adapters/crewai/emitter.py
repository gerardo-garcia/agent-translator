"""IR -> CrewAI JSON crew project (``crew.jsonc``, ``agents/*.jsonc``, ``tools/*.py``).

A CrewAI crew is flat: agents plus tasks. A sequential IR workflow becomes a sequential process
(one task per agent), a supervisor becomes a hierarchical process managed by the root agent. When
the IR came from CrewAI and an agent's instructions are unchanged, its original role/goal/
backstory and tasks are restored from ``extensions.crewai``; otherwise they are derived.
"""
from __future__ import annotations

import json
import re
from typing import Any

from ...ir import AgentIR, AgentSpec, Tool, ToolKind
from ...report import Report, Severity
from ..adk.common import py_name
from . import common as c

TOOL_CLASS = re.compile(r"^[A-Z]\w*Tool$")
PY_TYPE = {"string": "str", "number": "float", "integer": "int", "boolean": "bool",
           "array": "list", "object": "dict"}
INTERNAL = {"tasks", "name", "agentOrder", "managerKind", "managerAgent", "process",
            "manager_llm", "manager_agent"}


def dumps(d: Any) -> str:
    return json.dumps(d, indent=2, ensure_ascii=False) + "\n"


def tool_stub(fn: str, t: Tool) -> str:
    sch = t.parameters or {}
    props, req = sch.get("properties") or {}, set(sch.get("required") or [])
    cls = "".join(w.capitalize() for w in re.split(r"\W+", fn) if w) or "Tool"
    order = [p for p in props if p in req] + [p for p in props if p not in req]
    fields, sig = [], []
    for p in order:
        typ = PY_TYPE.get(props[p].get("type"), "str")
        desc = json.dumps(str(props[p].get("description") or p))
        if p in req:
            fields.append(f"    {py_name(p)}: {typ} = Field(..., description={desc})")
            sig.append(f"{py_name(p)}: {typ}")
        else:
            fields.append(f"    {py_name(p)}: Optional[{typ}] = Field(None, description={desc})")
            sig.append(f"{py_name(p)}: Optional[{typ}] = None")
    desc = json.dumps((t.description or t.name or t.id).strip())
    body = "\n".join(fields) or "    pass"
    return (f'"""Generated by agent-translator. Implement _run before use."""\n'
            "from typing import Optional, Type\n\n"
            "from crewai.tools import BaseTool\n"
            "from pydantic import BaseModel, Field\n\n\n"
            f"class {cls}Input(BaseModel):\n    \"\"\"Input schema of {fn}.\"\"\"\n{body}\n\n\n"
            f"class {cls}(BaseTool):\n"
            f"    name: str = {json.dumps(fn)}\n"
            f"    description: str = {desc}\n"
            f"    args_schema: Type[BaseModel] = {cls}Input\n\n"
            f"    def _run(self, {', '.join(sig)}) -> str:\n"
            f"        raise NotImplementedError({json.dumps(fn)})\n".replace(
                "_run(self, )", "_run(self)"))


class Project:
    def __init__(self, root: AgentSpec, ir: AgentIR, rep: Report):
        self.root, self.rep = root, rep
        self.by_id = {a.id: a for a in ir.agents}
        self.servers = {s["id"]: s for s in ir.resources.mcp_servers}
        self.files: dict[str, str] = {}
        self.stubs: dict[str, str] = {}
        self.names: dict[str, str] = {}          # agent id -> file/agent name
        self.restored: dict[str, bool] = {}

    # ------------------------------------------------------------- structure
    def _descendants(self) -> list[AgentSpec]:
        seen: dict[str, AgentSpec] = {}

        def walk(a: AgentSpec) -> None:
            for s in a.sub_agents:
                if s not in seen and s != self.root.id:
                    seen[s] = self.by_id[s]
                    walk(self.by_id[s])
        walk(self.root)
        return list(seen.values())

    def build(self) -> dict[str, str]:
        r = self.root
        workers = self._descendants() or [r]
        mode = r.collaboration.mode if r.sub_agents else "none"
        hierarchical = bool(r.sub_agents) and mode not in ("sequential", "parallel", "loop")
        path = f"agents[{r.id}]"
        if any(w.sub_agents for w in workers if w is not r):
            self.rep.add(Severity.lossy, "nesting-flattened", path,
                         "CrewAI crews are flat: nested sub-agents become peers of the crew")
        if mode == "loop":
            self.rep.add(Severity.lossy, "loop-single-pass", path,
                         "CrewAI has no loop: the agents run once in order")
        if mode == "handoff":
            self.rep.add(Severity.lossy, "handoff-as-manager", path,
                         "emitted as a hierarchical crew where the root manages and keeps control")
        if mode in ("sequential", "parallel", "loop") and (r.tools or r.instructions):
            self.rep.add(Severity.lossy, "workflow-agent-llm-dropped", path,
                         "a workflow agent has no LLM of its own in a CrewAI crew")
        for w in workers:
            self.names[w.id] = self._name(w, path)
        for w in workers:
            self.files[f"agents/{self.names[w.id]}.jsonc"] = dumps(self.agent_body(w))
        manager = r if hierarchical else None
        crew = self._crew(workers, mode, manager)
        if manager is not None:
            self._manager(manager, crew, workers)
        self.files["crew.jsonc"] = dumps(crew)
        for fn, src in self.stubs.items():
            self.files[f"tools/{fn}.py"] = src
        if self.stubs:
            self.files["tools/__init__.py"] = ""
        self.files["pyproject.toml"] = (
            f'[project]\nname = "{py_name(r.id).lower()}"\nversion = "0.1.0"\n'
            'requires-python = ">=3.10,<3.14"\ndependencies = ["crewai[tools]"]\n\n'
            "[build-system]\nrequires = [\"hatchling\"]\nbuild-backend = \"hatchling.build\"\n\n"
            "[tool.hatch.build.targets.wheel]\n"
            'only-include = ["agents", "crew.jsonc", "tools"]\n\n'
            '[tool.crewai]\ntype = "crew"\ndefinition = "crew.jsonc"\n')
        return self.files

    def _name(self, a: AgentSpec, path: str) -> str:
        n = re.sub(r"[^A-Za-z0-9_-]+", "_", a.id).strip("_") or "agent"
        if n != a.id:
            self.rep.add(Severity.warning, "name-sanitized", f"agents[{a.id}]",
                         f"{a.id!r} -> {n!r} (agent file name)")
        return n

    # ------------------------------------------------------------------ crew
    def _crew(self, workers: list[AgentSpec], mode: str, manager: AgentSpec | None) -> dict:
        ext = self.root.extensions.get("crewai", {}).get("crew", {})
        names = [self.names[w.id] for w in workers]
        reuse = (ext.get("tasks") and all(self.restored.get(w.id) for w in workers)
                 and set(ext.get("agentOrder", [])) == set(names)
                 and (manager is not None) == (ext.get("managerKind") is not None))
        crew: dict[str, Any] = {k: v for k, v in ext.items() if k not in INTERNAL}
        crew["name"] = ext.get("name") or self.root.name
        crew["agents"] = names
        if reuse:
            crew["tasks"] = ext["tasks"]
        else:
            crew["tasks"] = self._tasks(workers, mode, manager)
            if "request" in json.dumps(crew["tasks"]):
                crew.setdefault("inputs", {"request": "Describe the task here."})
        crew["process"] = "hierarchical" if manager is not None else "sequential"
        if any(w.memory.enabled for w in workers) or self.root.memory.enabled:
            crew["memory"] = True
        return crew

    def _tasks(self, workers: list[AgentSpec], mode: str, manager: AgentSpec | None) -> list:
        if manager is not None:
            self.rep.add(Severity.info, "task-synthesized", f"agents[{self.root.id}]",
                         "one task for the whole request, delegated by the manager")
            return [{"name": "main_task",
                     "description": "Handle the following request: {request}",
                     "expected_output": "A complete and accurate answer to the request."}]
        tasks = []
        for w in workers:
            t: dict[str, Any] = {
                "name": f"{self.names[w.id]}_task",
                "description": "Do your part of this request: {request}",
                "expected_output": "Your part of the result, complete and accurate.",
                "agent": self.names[w.id]}
            if mode == "parallel":
                t["async_execution"] = True
            tasks.append(t)
        self.rep.add(Severity.info, "task-synthesized", f"agents[{self.root.id}]",
                     f"{len(tasks)} task(s) derived from the agents (CrewAI needs explicit tasks)")
        return tasks

    def _manager(self, m: AgentSpec, crew: dict, workers: list[AgentSpec]) -> None:
        ext = m.extensions.get("crewai", {}).get("crew", {})
        as_agent = ext.get("managerKind") == "agent" or (
            ext.get("managerKind") is None and not m.tools and m.instructions)
        if as_agent and (m.tools):
            self.rep.add(Severity.lossy, "manager-tools-dropped", f"agents[{m.id}]",
                         "a CrewAI manager agent cannot use tools: it keeps the persona only")
        if as_agent:
            name = self._name(m, f"agents[{m.id}]")
            self.names[m.id] = name
            body = self.agent_body(m, manager=True)
            self.files[f"agents/{name}.jsonc"] = dumps(body)
            crew["manager_agent"] = name
        else:
            llm = self._llm(m, f"agents[{m.id}]")
            if llm is None:
                donor = next((w for w in workers if w.model.id), None)
                if donor is not None:
                    llm = self._llm(donor, f"agents[{donor.id}]")
                    self.rep.add(Severity.warning, "manager-model-borrowed", f"agents[{m.id}]",
                                 f"the manager has no model: using {donor.id}'s")
                else:
                    llm = "openai/gpt-4o-mini"
                    self.rep.add(Severity.manual, "manager-model-required", f"agents[{m.id}]",
                                 "a hierarchical crew needs manager_llm and no model is known: "
                                 f"{llm!r} is a placeholder")
            crew["manager_llm"] = llm
            if m.instructions and ext.get("managerKind") != "llm":
                self.rep.add(Severity.lossy, "manager-instructions-dropped", f"agents[{m.id}]",
                             "the manager is a model only (manager_llm); its instructions are "
                             "not used")

    # ----------------------------------------------------------------- agents
    def agent_body(self, a: AgentSpec, manager: bool = False) -> dict[str, Any]:
        path = f"agents[{a.id}]"
        ext = a.extensions.get("crewai", {})
        persona, tasks = ext.get("persona"), ext.get("tasks") or []
        restored = bool(persona) and (a.instructions or "") == c.compose(persona, tasks)
        self.restored[a.id] = restored
        if restored:
            body: dict[str, Any] = {k: persona.get(k) for k in c.PERSONA_KEYS}
        else:
            if not a.instructions:
                self.rep.add(Severity.warning, "instruction-missing", f"{path}.instructions",
                             "no instructions: the backstory only names the agent")
            body = {"role": a.name, "goal": a.description or c.DEFAULT_GOAL,
                    "backstory": a.instructions or f"You are {a.name}."}
        llm = self._llm(a, path)
        if llm is not None:
            body["llm"] = llm
        elif not a.extensions.get("crewai"):
            self.rep.add(Severity.warning, "model-missing", f"{path}.model",
                         "no model: CrewAI will use its default (OPENAI_MODEL_NAME)")
        tools: list[Any] = []
        mcps: list[Any] = []
        if not manager:
            self._tools(a, path, tools, mcps)
        if tools:
            body["tools"] = tools
        if mcps:
            body["mcps"] = mcps
        for k, v in (ext.get("settings") or {}).items():
            body.setdefault(k, v)
        if "settings" not in body and not ext:
            body["settings"] = {"allow_delegation": False}
        if a.guardrails:
            one = a.guardrails[0].get("instruction") if len(a.guardrails) == 1 else None
            if isinstance(one, str):
                body["guardrail"] = one
            else:
                self.rep.add(Severity.lossy, "guardrails-dropped", f"{path}.guardrails",
                             "only a single text guardrail maps to CrewAI's `guardrail`")
        return body

    def _llm(self, a: AgentSpec, path: str) -> Any:
        m = a.model
        if not m.id:
            return None
        s = c.model_string(m.provider, m.id)
        if s is None:
            keep = m.id if "/" in m.id else None
            self.rep.add(Severity.manual, "model-unmapped", f"{path}.model",
                         f"model {m.id!r} ({m.provider}) has no known LiteLLM prefix; copied "
                         "as-is, write it as 'provider/model'")
            s = keep or m.id
        extra = a.extensions.get("crewai", {}).get("llmExtra") or {}
        extra = {k: v for k, v in extra.items() if k != "prefix"}
        if not m.params and not extra:
            return s
        obj: dict[str, Any] = {"model": s}
        for k, v in m.params.items():
            if k in c.LLM_PARAMS.values() and k != "top_k":
                obj[k] = v
            else:
                self.rep.add(Severity.lossy, "param-dropped", f"{path}.model.params.{k}",
                             "not a CrewAI LLM argument")
        obj.update(extra)
        return obj

    def _tools(self, a: AgentSpec, path: str, tools: list[Any], mcps: list[Any]) -> None:
        for t in a.tools:
            tp = f"{path}.tools[{t.id}]"
            tx = t.extensions.get("crewai", {})
            if t.requires_confirmation:
                self.rep.add(Severity.lossy, "confirmation-dropped", tp,
                             "CrewAI approves per task (`human_input`), not per tool call")
            if tx.get("ref") or tx.get("def"):
                tools.append(tx.get("def") or tx["ref"])
                continue
            if t.kind in (ToolKind.function, ToolKind.openapi, ToolKind.knowledge):
                fn = py_name(t.name or t.id).lower()
                if t.kind is ToolKind.knowledge:
                    t = t.model_copy(update={
                        "description": t.description or f"Search {t.kb_ref or t.id}.",
                        "parameters": {"properties": {"query": {"type": "string"}},
                                       "required": ["query"]}})
                if t.kind is ToolKind.openapi:
                    self.rep.add(Severity.lossy, "openapi-spec-dropped", tp,
                                 "the OpenAPI spec is not translated; the stub must call the API")
                self.stubs.setdefault(fn, tool_stub(fn, t))
                tools.append(f"custom:{fn}")
                self.rep.add(Severity.manual, "function-stub-generated", tp,
                             f"tools/{fn}.py is a stub: implement _run "
                             f"(original: {t.impl_ref or t.kb_ref or 'unknown'})")
            elif t.kind is ToolKind.builtin and t.name and TOOL_CLASS.match(t.name):
                tools.append(t.name)
                self.rep.add(Severity.warning, "builtin-tool-name", tp,
                             f"{t.name!r} is used as a crewai_tools class name; check it exists")
            elif t.kind is ToolKind.mcp:
                s = self.servers.get(t.server_ref or "")
                if not s or not s.get("url"):
                    self.rep.add(Severity.manual, "mcp-server-undefined", tp,
                                 f"no URL known for MCP server {t.server_ref!r}; dropped")
                    continue
                if s.get("headers"):
                    self.rep.add(Severity.manual, "mcp-headers-dropped", tp,
                                 "headers (possibly credentials) are not copied")
                mcps.extend([f"{s['url']}#{n}" for n in t.tool_names] or [s["url"]])
            else:
                self.rep.add(Severity.manual, "tool-unsupported", tp,
                             f"{t.kind.value} tools have no CrewAI equivalent; dropped")
        for r in a.remote_agents:
            self.rep.add(Severity.manual, "remote-agent-unsupported",
                         f"{path}.remote_agents[{r.id}]",
                         "CrewAI A2A agents are not generated; configure `a2a` by hand")


def emit_project(ir: AgentIR, rep: Report) -> dict[str, str]:
    children = {s for a in ir.agents for s in a.sub_agents}
    roots = [a for a in ir.agents if a.id not in children] or ir.agents[:1]
    files: dict[str, str] = {}
    for r in roots:
        prefix = "" if len(roots) == 1 else f"{c.slug(r.id)}/"
        for rel, text in Project(r, ir, rep).build().items():
            files[prefix + rel] = text
    return files
