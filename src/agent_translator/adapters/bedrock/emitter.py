"""IR -> CloudFormation template with AWS::Bedrock::Agent resources."""
from __future__ import annotations

import io
import math
import re
from typing import Any

from ...ir import AgentIR, AgentSpec, Tool, ToolKind
from ...report import Report, Severity
from . import cfn

BEDROCK_MODEL = re.compile(
    r"^(?:(?:us|eu|apac|global|us-gov|jp|au|ca)\.)?(?:anthropic|amazon|meta|mistral|cohere|ai21|"
    r"deepseek|openai|stability|writer|qwen)\.[\w.:-]+$|^arn:")
BUILTIN_GROUP = {"AMAZON.UserInput": "UserInputAction",
                 "AMAZON.CodeInterpreter": "CodeInterpreterAction"}
LAMBDA_ARN = re.compile(r"^arn:aws[\w-]*:lambda:")
ALIAS_ARN = re.compile(r"^arn:aws[\w-]*:bedrock:[\w-]+:\d{12}:agent-alias/")
PARAM_TYPE = {"string": "string", "number": "number", "integer": "integer",
              "boolean": "boolean", "array": "array"}


class Ctx:
    """Collects template Parameters and decides which references may stay as they were."""

    def __init__(self, rep: Report):
        self.rep = rep
        self.parameters: dict[str, dict] = {}
        self.local: set[str] = set()      # logical ids emitted in this template
        self.known: dict[str, dict] = {}  # parameter definitions carried from the source

    def param(self, name: str, desc: str, default: str | None = None) -> dict:
        name = re.sub(r"[^0-9a-zA-Z]", "", name) or "Param"
        p: dict[str, Any] = {"Type": "String", "Description": desc}
        if default is not None:
            p["Default"] = default
        self.parameters.setdefault(name, p)
        return {"Ref": name}

    def keep(self, raw: Any, pname: str, what: str, path: str) -> Any:
        """Keep an intrinsic if everything it needs exists here; otherwise ask for a parameter."""
        need = cfn.refs_in(raw)
        free = {n for n in need if not cfn.is_pseudo(n) and n not in self.local
                and n not in self.known}
        if not free:
            for n in need:
                if n in self.known:
                    self.parameters.setdefault(n, self.known[n])
            return raw
        self.rep.add(Severity.manual, "reference-externalised", path,
                     f"{what} referenced {sorted(free)}, which this template does not define; "
                     f"it is now the parameter {pname}")
        return self.param(pname, f"{what} (was a reference to {min(free)})")


def clip(v: Any, limit: int, rep: Report, path: str) -> Any:
    """Bedrock caps description lengths; cut with a notice instead of failing at deploy time."""
    if isinstance(v, str) and len(v) > limit:
        rep.add(Severity.lossy, "text-truncated", path, f"{len(v)} chars cut to {limit}")
        return v[:limit - 1].rstrip() + "…"
    return v


def _bx(x: Any) -> dict:
    return x.extensions.get("bedrock", {})


def _group_name(name: str, used: set[str]) -> str:
    n, cand = 2, cfn.safe_name(name)
    while cand in used:
        cand, n = f"{cfn.safe_name(name, 96)}-{n}", n + 1
    used.add(cand)
    return cand


def emit(ir: AgentIR, rep: Report) -> dict:
    ctx = Ctx(rep)
    lids = {a.id: cfn.logical_id(a.id) for a in ir.agents}
    if len(set(lids.values())) != len(lids):
        rep.add(Severity.error, "id-collision", "agents",
                "agent ids collapse to the same CloudFormation logical id")
        return {}
    for a in ir.agents:
        ctx.known.update(_bx(a).get("parameters", {}))
    ctx.local |= set(lids.values()) | {f"{v}Alias" for v in lids.values()}
    for a in ir.agents:
        g = _bx(a).get("guardrailResource")
        if g:
            ctx.local.add(g["logicalId"])

    resources: dict[str, Any] = {}
    outputs: dict[str, Any] = {}
    _check_cycles(ir, rep)
    for a in ir.agents:
        L = lids[a.id]
        resources[L] = {"Type": cfn.AGENT, "Properties": _agent(a, L, lids, ctx, rep)}
        alias = {"AgentId": {"Fn::GetAtt": [L, "AgentId"]},
                 "AgentAliasName": _bx(a).get("aliasName", "live")}
        resources[f"{L}Alias"] = {"Type": cfn.ALIAS, "Properties": alias}
        outputs[f"{L}AliasArn"] = {"Value": {"Fn::GetAtt": [f"{L}Alias", "AgentAliasArn"]}}
        g = _bx(a).get("guardrailResource")
        if g:
            resources.setdefault(g["logicalId"], g["resource"])
    rep.add(Severity.info, "alias-generated", "Resources",
            "one AgentAlias per agent so that it can be invoked and used as a collaborator")
    tpl: dict[str, Any] = {"AWSTemplateFormatVersion": "2010-09-09",
                           "Description": "Generated by agent-translator"}
    if ctx.parameters:
        tpl["Parameters"] = ctx.parameters
    tpl["Resources"] = resources
    tpl["Outputs"] = outputs
    return tpl


def _check_cycles(ir: AgentIR, rep: Report) -> None:
    graph = {a.id: a.sub_agents for a in ir.agents}
    state: dict[str, int] = {}

    def visit(n: str) -> bool:
        if state.get(n) == 1:
            return True
        if state.get(n) == 2:
            return False
        state[n] = 1
        if any(visit(m) for m in graph.get(n, [])):
            return True
        state[n] = 2
        return False
    if any(visit(n) for n in graph):
        rep.add(Severity.error, "collaboration-cycle", "agents",
                "CloudFormation cannot express cyclic collaboration (alias ARNs form a loop)")


# --------------------------------------------------------------------- agent
def _text(a: AgentSpec, key: str, value: str | None, pname: str, ctx: Ctx, path: str) -> Any:
    ix = _bx(a).get("intrinsics", {}).get(key)
    if ix and value == ix["resolved"]:
        return ctx.keep(ix["raw"], pname, key, path)
    return value


def _agent(a: AgentSpec, L: str, lids: dict[str, str], ctx: Ctx, rep: Report) -> dict:
    path = f"agents[{a.id}]"
    bx = _bx(a)
    props: dict[str, Any] = {}
    name = cfn.safe_name(a.name)
    if name != a.name:
        rep.add(Severity.warning, "name-sanitized", f"{path}.name",
                f"{a.name!r} -> {name!r} (Bedrock allows letters, digits, '-' and '_')")
    props["AgentName"] = _text(a, "AgentName", a.name, f"{L}AgentName", ctx, path) \
        if name == a.name else name
    if a.description:
        props["Description"] = clip(
            _text(a, "Description", a.description, f"{L}Description", ctx, path),
            200, rep, f"{path}.description")
    if a.instructions:
        text = a.instructions
        if len(text) < 40:
            text = f"{text.rstrip()} Answer the user's requests helpfully and accurately."
            rep.add(Severity.warning, "instruction-padded", f"{path}.instructions",
                    "Bedrock requires at least 40 characters: a generic sentence was appended")
        props["Instruction"] = _text(a, "Instruction", text, f"{L}Instruction", ctx, path)
    else:
        rep.add(Severity.warning, "instruction-missing", f"{path}.instructions",
                "Bedrock needs an instruction to prepare the agent")
    props["FoundationModel"] = _model(a, L, ctx, rep, path)

    role = (bx.get("properties") or {}).get("AgentResourceRoleArn")
    if role is not None:
        props["AgentResourceRoleArn"] = ctx.keep(role, f"{L}AgentResourceRoleArn",
                                                 "service role", path)
    else:
        props["AgentResourceRoleArn"] = ctx.param(
            f"{L}AgentResourceRoleArn", "ARN of the IAM service role the agent assumes")
        rep.add(Severity.manual, "role-required", path,
                "an IAM service role with bedrock:InvokeModel is needed; pass its ARN")
    for k, v in (bx.get("properties") or {}).items():
        if k != "AgentResourceRoleArn":
            props[k] = ctx.keep(v, f"{L}{k}", k, f"{path}.{k}")
    props.setdefault("AutoPrepare", True)

    groups, kbs = _tools(a, L, ctx, rep, path)
    if groups:
        props["ActionGroups"] = groups
    if kbs:
        props["KnowledgeBases"] = kbs

    collabs = _collaborators(a, L, lids, ctx, rep, path)
    if collabs:
        props["AgentCollaboration"] = "SUPERVISOR_ROUTER" if a.collaboration.mode == "router" \
            else "SUPERVISOR"
        props["AgentCollaborators"] = collabs
        if a.collaboration.mode in ("sequential", "parallel", "loop", "handoff"):
            rep.add(Severity.lossy, "collaboration-mode", path,
                    f"{a.collaboration.mode} collaboration does not exist in Bedrock; using SUPERVISOR")
    if a.guardrails:
        props["GuardrailConfiguration"] = _guardrail(a, L, ctx, rep, path)
    if a.memory.enabled:
        cfg = dict(bx.get("memoryConfiguration") or {})
        cfg.setdefault("EnabledMemoryTypes", ["SESSION_SUMMARY"])
        if a.memory.ttl_seconds:
            cfg["StorageDays"] = math.ceil(a.memory.ttl_seconds / 86400)
        props["MemoryConfiguration"] = cfg
    return props


def _model(a: AgentSpec, L: str, ctx: Ctx, rep: Report, path: str) -> Any:
    m = a.model
    ix = _bx(a).get("intrinsics", {}).get("FoundationModel")
    if m.id and ix and m.id == ix["resolved"]:
        return ctx.keep(ix["raw"], f"{L}FoundationModel", "model", path)
    if m.id and BEDROCK_MODEL.match(m.id):
        return m.id
    rep.add(Severity.manual, "model-required", f"{path}.model",
            f"model {m.id!r} ({m.provider}) is not a Bedrock model id; choose one "
            f"(see -O model_policy=tier)")
    return ctx.param(f"{L}FoundationModel",
                     f"Bedrock model id or inference profile (source model: {m.id})")


def _guardrail(a: AgentSpec, L: str, ctx: Ctx, rep: Report, path: str) -> Any:
    raw = _bx(a).get("guardrailConfiguration")
    if raw:
        return ctx.keep(raw, f"{L}GuardrailConfiguration", "guardrail", path) \
            if cfn.is_intrinsic(raw) else {
                k: ctx.keep(v, f"{L}{k}", k, path) for k, v in raw.items()}
    g = a.guardrails[0]
    if len(a.guardrails) > 1:
        rep.add(Severity.lossy, "guardrail-multiple", path, "Bedrock agents take one guardrail")
    if g.get("provider") not in (None, "bedrock"):
        rep.add(Severity.lossy, "guardrail-dropped", path, "non-Bedrock guardrail dropped")
    return {"GuardrailIdentifier": ctx.param(f"{L}GuardrailIdentifier",
                                            "Bedrock guardrail id or ARN"),
            "GuardrailVersion": ctx.param(f"{L}GuardrailVersion", "Guardrail version",
                                          str(g.get("version") or "DRAFT"))}


# ---------------------------------------------------------------------- tools
def _executor(t: Tool, L: str, ctx: Ctx, rep: Report, path: str) -> dict:
    if t.impl_ref and LAMBDA_ARN.match(t.impl_ref):
        return {"Lambda": t.impl_ref}
    raw = _bx(t).get("executor")
    pname = f"{L}{cfn.logical_id(t.id)}Lambda"
    if isinstance(raw, dict) and raw.get("CustomControl"):
        return raw
    if isinstance(raw, dict) and "Lambda" in raw:
        return {"Lambda": ctx.keep(raw["Lambda"], pname, "Lambda function", path)}
    rep.add(Severity.manual, "executor-required", path,
            f"tool {t.id!r} has no Lambda; pass the ARN of one that implements it")
    return {"Lambda": ctx.param(pname, f"ARN of the Lambda function implementing {t.id}")}


def _tools(a: AgentSpec, L: str, ctx: Ctx, rep: Report, path: str):
    groups: list[dict] = []
    by_name: dict[str, dict] = {}
    used: set[str] = set()
    kbs: list[dict] = []
    for t in a.tools:
        tp = f"{path}.tools[{t.id}]"
        bx = _bx(t)
        if t.requires_confirmation and t.kind not in (ToolKind.function, ToolKind.mcp):
            rep.add(Severity.lossy, "confirmation-dropped", tp,
                    f"Bedrock confirms individual functions only; {t.kind.value} tool "
                    f"{t.id!r} will run without confirmation")
        if t.kind is ToolKind.builtin:
            sig = t.name if t.name in BUILTIN_GROUP else None
            if not sig:
                rep.add(Severity.lossy, "tool-dropped", tp,
                        f"built-in tool {t.name or t.id!r} has no Bedrock equivalent")
                continue
            g = {"ActionGroupName": _group_name(bx.get("actionGroup", BUILTIN_GROUP[sig]), used),
                 "ParentActionGroupSignature": sig, "ActionGroupState": "ENABLED"}
            groups.append(g)
        elif t.kind is ToolKind.openapi:
            groups.append(_openapi_group(t, L, ctx, rep, tp, used))
        elif t.kind is ToolKind.function:
            gname = bx.get("actionGroup", "functions")
            g = by_name.get(gname)
            if g is None:
                g = {"ActionGroupName": _group_name(gname, used),
                     "ActionGroupExecutor": _executor(t, L, ctx, rep, tp)}
                if bx.get("groupDescription"):
                    g["Description"] = bx["groupDescription"]
                g.update(bx.get("props", {}))
                g["FunctionSchema"] = {"Functions": []}
                by_name[gname] = g
                groups.append(g)
            g["FunctionSchema"]["Functions"].append(_function(t, rep, tp))
        elif t.kind is ToolKind.knowledge:
            kbs.append(_knowledge(t, L, ctx, rep, tp))
        elif t.kind is ToolKind.mcp:
            rep.add(Severity.lossy, "tool-dropped", tp,
                    f"MCP server {t.server_ref!r}: Bedrock Agents cannot call MCP directly. "
                    "Expose it through an action group (e.g. via AgentCore Gateway) manually")
        elif t.kind is ToolKind.agent:
            continue      # covered by collaborators
    return groups, kbs


def _openapi_group(t: Tool, L: str, ctx: Ctx, rep: Report, path: str, used: set[str]) -> dict:
    bx = _bx(t)
    g: dict[str, Any] = {"ActionGroupName": _group_name(bx.get("actionGroup", t.name or t.id), used),
                         "ActionGroupExecutor": _executor(t, L, ctx, rep, path)}
    if t.description:
        g["Description"] = clip(t.description, 200, rep, f"{path}.description")
    g.update(bx.get("props", {}))
    if isinstance(t.spec, dict | list):
        y = cfn.dumper()
        buf = io.StringIO()
        y.dump(cfn.lit(t.spec), buf)
        g["ApiSchema"] = {"Payload": buf.getvalue()}
    elif isinstance(t.spec, str) and t.spec.strip():
        g["ApiSchema"] = {"Payload": t.spec}
    elif bx.get("apiSchema"):
        raw = bx["apiSchema"]
        s3 = raw.get("S3") if isinstance(raw, dict) else None
        if isinstance(s3, dict):
            g["ApiSchema"] = {"S3": {k: ctx.keep(v, f"{L}{cfn.logical_id(t.id)}{k}",
                                                 f"S3 {k}", path) for k, v in s3.items()}}
        else:
            g["ApiSchema"] = ctx.keep(raw, f"{L}{cfn.logical_id(t.id)}ApiSchema", "ApiSchema", path)
    else:
        rep.add(Severity.manual, "schema-required", path, f"tool {t.id!r} has no OpenAPI spec")
    return g


def _function(t: Tool, rep: Report, path: str) -> dict:
    f: dict[str, Any] = {"Name": cfn.safe_name(t.name or t.id)}
    if t.description:
        f["Description"] = clip(t.description, 1200, rep, f"{path}.description")
    sch = t.parameters or {}
    req = set(sch.get("required", []))
    params: dict[str, Any] = {}
    for pn, ps in (sch.get("properties") or {}).items():
        typ = ps.get("type")
        if typ not in PARAM_TYPE:
            rep.add(Severity.lossy, "parameter-type-coerced", f"{path}.{pn}",
                    f"type {typ!r} is not supported by Bedrock functions; using string")
            typ = "string"
        d: dict[str, Any] = {"Type": typ}
        if ps.get("description"):
            d["Description"] = clip(ps["description"], 500, rep, f"{path}.{pn}")
        if pn in req:
            d["Required"] = True
        params[pn] = d
    if params:
        f["Parameters"] = params
    if t.requires_confirmation is not None:
        f["RequireConfirmation"] = "ENABLED" if t.requires_confirmation else "DISABLED"
    return f


def _knowledge(t: Tool, L: str, ctx: Ctx, rep: Report, path: str) -> dict:
    bx = dict(_bx(t))
    kb: dict[str, Any] = {k: v for k, v in bx.items() if k in ("KnowledgeBaseState",)}
    if t.kb_ref and re.fullmatch(r"[0-9a-zA-Z]{10}", t.kb_ref):
        kb["KnowledgeBaseId"] = t.kb_ref
    elif "KnowledgeBaseId" in bx:
        kb["KnowledgeBaseId"] = ctx.keep(bx["KnowledgeBaseId"],
                                         f"{L}{cfn.logical_id(t.id)}KnowledgeBaseId",
                                         "knowledge base id", path)
    else:
        rep.add(Severity.manual, "knowledge-base-required", path,
                f"{t.kb_ref!r} is not a Bedrock knowledge base id; create one and pass its id")
        kb["KnowledgeBaseId"] = ctx.param(f"{L}{cfn.logical_id(t.id)}KnowledgeBaseId",
                                          f"Bedrock knowledge base id (source: {t.kb_ref})")
    kb["Description"] = clip(t.description or t.name or t.id, 200, rep, f"{path}.description")
    if t.top_k is not None:
        rep.add(Severity.lossy, "top-k-dropped", path,
                "numberOfResults is set at invocation time in Bedrock, not in the agent")
    return kb


# --------------------------------------------------------------- collaborators
def _collaborators(a: AgentSpec, L: str, lids: dict[str, str], ctx: Ctx, rep: Report,
                   path: str) -> list[dict]:
    bx = _bx(a)
    out = []
    byid = {x for x in lids}
    for sid in a.sub_agents:
        if sid not in byid:
            continue
        props = bx.get("collaborators", {}).get(sid, {})
        name = props.get("name") or sid
        instr = a.collaboration.instructions.get(sid) or props.get("instruction")
        if not instr:
            instr = f"Delegate to {name} the tasks that fall within its expertise."
            rep.add(Severity.warning, "collaboration-instruction-generated", f"{path}.{sid}",
                    "Bedrock requires a collaboration instruction; a generic one was written")
        c: dict[str, Any] = {
            "CollaboratorName": cfn.safe_name(name if isinstance(name, str) else sid),
            "AgentDescriptor": {"AliasArn": {"Fn::GetAtt": [f"{lids[sid]}Alias", "AgentAliasArn"]}},
            "CollaborationInstruction": instr}
        if "relayConversationHistory" in props:
            c["RelayConversationHistory"] = props["relayConversationHistory"]
        out.append(c)
    for i, r in enumerate(a.remote_agents):
        rp = f"{path}.remote_agents[{r.id}]"
        rx = r.extensions.get("bedrock", {})
        if r.ref and ALIAS_ARN.match(r.ref):
            alias: Any = r.ref
        elif rx.get("aliasArn") is not None:
            alias = ctx.keep(rx["aliasArn"], f"{L}Collaborator{i + 1}AliasArn",
                             "collaborator alias", rp)
        else:
            rep.add(Severity.manual, "remote-agent-ref-required", rp,
                    f"{r.name!r} has no Bedrock agent alias ARN ({r.ref or 'no locator'}); "
                    "deploy it as a Bedrock agent and pass its alias ARN")
            alias = ctx.param(f"{L}Collaborator{i + 1}AliasArn",
                              f"Alias ARN of the Bedrock agent standing for {r.name}")
        c = {"CollaboratorName": cfn.safe_name(r.name),
             "AgentDescriptor": {"AliasArn": alias},
             "CollaborationInstruction": r.instruction or r.description
             or f"Delegate to {r.name} the tasks that fall within its expertise."}
        if "relayConversationHistory" in rx:
            c["RelayConversationHistory"] = rx["relayConversationHistory"]
        out.append(c)
    if a.sub_agents and not out:
        rep.add(Severity.error, "collaborators-missing", path, "sub-agents could not be emitted")
    return out
